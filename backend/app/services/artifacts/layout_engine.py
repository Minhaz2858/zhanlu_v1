"""PHASE 1 layout engine — single source of truth for deck slide layout.

This module owns every shape and textbox placed on a PowerPoint slide
generated by the Zhanlu agent. Both the in-process renderer
(``app/services/artifacts/exporters/pptx_export.py``) and the sandbox
renderer (``app/services/sandbox/sandbox_runner.py``) delegate here, so
chat-driven and exporter-driven decks share the same look.

DESIGN GOALS (echoing the spec):

* Varied layout per slide — 12 layout types: cover, agenda, kpi_grid,
  chart_full, chart_with_bullets, findings_cards, insights_bullets,
  recommendations, data_table, methodology, section_divider, closing.
* Assertion-style headlines — each slide's title is rewritten via
  ``_assertify_headline()`` unless the planner already supplied a
  sentence-form title (≥4 words OR ends with punctuation).
* Body budgets — at most 5 bullets, ~12 words / bullet, body ≥14 pt.
* Branded charts — ``charts.branded_charts.style_chart``.
* Top-8 + top-3-highlight data table — see ``_layout_data_table``.
* Subtle slide numbers — see ``add_slide_number``. No "Generated by...".

USAGE:

    from app.services.artifacts.layout_engine import render
    pptx_bytes = render(plan, rows, ctx)

Where ``plan`` is a ``synexia.contracts.DeckPlan`` instance (or a
plain dict with the same shape), ``rows`` is the underlying data and
``ctx`` is a dict with ``theme_tokens`` and ``style_recipe``.
"""

