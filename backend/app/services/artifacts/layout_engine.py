def _add_textbox(
    slide, left_in: float, top_in: float, width_in: float, height_in: float,
    text: str, size: int, bold: bool = False, color: RGBColor | None = None,
    align: PP_ALIGN = PP_ALIGN.LEFT,
):
    tb = slide.shapes.add_textbox(
        Inches(left_in), Inches(top_in), Inches(width_in), Inches(height_in),
    )
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = Inches(0)
    tf.margin_right = Inches(0)
    tf.margin_top = Inches(0)
    tf.margin_bottom = Inches(0)
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text or ""
    run.font.name = _font_for(text, "heading" if bold else "body")
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    return tb


def _add_rect(
    slide, left_in: float, top_in: float, width_in: float, height_in: float,
    fill: RGBColor | None = None, border: RGBColor | None = None,
    rounded: bool = False, radius_in: float = 0.08,
):
    shape_type = MSO_SHAPE.ROUNDED_RECTANGLE if rounded else MSO_SHAPE.RECTANGLE
    shape = slide.shapes.add_shape(
        shape_type, Inches(left_in), Inches(top_in),
        Inches(width_in), Inches(height_in),
    )
    shape.shadow.inherit = False
    if fill is not None:
        shape.fill.solid()
        shape.fill.fore_color.rgb = fill
    else:
        shape.fill.background()
    if border is not None:
        shape.line.color.rgb = border
        shape.line.width = Pt(0.75)
    else:
        shape.line.fill.background()
    shape.text_frame.text = ""
    if rounded:
        try:
            shorter = min(width_in, height_in) or 1.0
            shape.adjustments[0] = max(0.0, min(0.5, radius_in / shorter))
        except Exception:
            pass
    return shape


def _section_title(slide, text: str, theme: dict) -> None:
    _add_textbox(
        slide, MARGIN_IN, 0.5, SLIDE_W_IN - 2 * MARGIN_IN, 0.8,
        text, TITLE_PT, bold=True,
        color=_rgb(theme, "text", "#0F172A"),
    )
    _add_rect(
        slide, MARGIN_IN, 1.25, 1.2, 0.05,
        fill=_rgb(theme, "primary", "#2563EB"),
    )


def _coerce(v) -> float:
    if v is None or isinstance(v, bool):
        return 0
    if isinstance(v, (int, float)):
        return float(v)
    try:
        return float(str(v).replace(",", "").strip())
    except (ValueError, TypeError):
        return 0


def _cap_table_rows(
    rows: list[dict[str, Any]],
    cols: list[str],
    sort_col: Optional[str],
    cap: int = 8,
) -> list[dict[str, Any]]:
    """Cap a table at ``cap`` rows, folding the remainder into one "Other" row.

    Mirrors :func:`cap_chart_categories` so tables and native charts obey the
    same 8 + Other rule.  Rows are ranked by ``sort_col`` when present (largest
    first); otherwise the first 8 rows are kept in order.  Numeric columns are
    summed into the "Other" row; the first (label) column becomes ``"Other"``.
    """
    if not rows or len(rows) <= cap:
        return list(rows)
    if sort_col:
        ordered = sorted(rows, key=lambda r: _coerce(r.get(sort_col)), reverse=True)
    else:
        ordered = list(rows)
    kept = [dict(r) for r in ordered[:cap]]
    rest = ordered[cap:]
    if not rest:
        return kept
    other: dict[str, Any] = {}
    for ci, c in enumerate(cols):
        if ci == 0:
            other[c] = "Other"
        else:
            other[c] = sum(_coerce(r.get(c)) for r in rest)
    kept.append(other)
    return kept


