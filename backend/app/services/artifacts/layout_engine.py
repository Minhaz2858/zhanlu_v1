def _layout_data_table(slide, sp, theme, idx, total) -> None:
    _section_title(slide, _assertify_headline(sp.get("title", "Data"), "data_table"), theme)
    rows = sp.get("table_rows") or []
    cols = sp.get("table_cols") or []
    if not rows or not cols:
        _add_textbox(slide, MARGIN_IN, 3.0, 8, 1.0,
                     "No table data available.", BODY_PT,
                     color=_rgb(theme, "muted", "#64748B"))
        return

    # --- Determine the "most-relevant numeric column" so we can sort ---
    def _numeric_score(c: str) -> float:
        score = 0.0
        for r in rows:
            v = r.get(c)
            if v is None:
                continue
            try:
                float(str(v).replace(",", ""))
                score += 1
            except (ValueError, TypeError):
                pass
        return score

    sort_col = None
    sort_desc = True
    for c in cols:
        if _numeric_score(c) >= max(2, 0.5 * len(rows)):
            sort_col = c
            break

    if sort_col:
        rows = sorted(
            rows,
            key=lambda r: _coerce(r.get(sort_col)),
            reverse=sort_desc,
        )

    # PHASE 1 acceptance + Fix #3: cap at the SAME top-8 limit the charts use,
    # folding the remainder into an "Other" row so the table and the native
    # chart always show the identical category rule (8 + Other).
    top_rows = _cap_table_rows(rows, cols, sort_col, 8)

    # --- Table shape ---
    n_data_rows = len(top_rows)
    n_rows = n_data_rows + 1
    n_cols = len(cols)
    table_w = SLIDE_W_IN - 2 * MARGIN_IN
    table_h = SLIDE_H_IN - 1.8 - 0.4
    table_shape = slide.shapes.add_table(
        n_rows, n_cols,
        Inches(MARGIN_IN), Inches(1.6),
        Inches(table_w), Inches(table_h),
    )
    table = table_shape.table
    # Set relative widths: first column slightly wider.
    if n_cols > 1:
        table.columns[0].width = Inches(table_w * 0.32)
        rest = table_w * 0.68 / (n_cols - 1)
        for cidx in range(1, n_cols):
            table.columns[cidx].width = Inches(rest)
    # Header row
    for ci, c in enumerate(cols):
        cell = table.cell(0, ci)
        cell.text = c
        for p in cell.text_frame.paragraphs:
            for r in p.runs:
                r.font.name = _font_for(r.text, "body")
                r.font.size = Pt(CAPTION_PT)
                r.font.bold = True
                r.font.color.rgb = _rgb(theme, "text", "#0F172A")
        cell.fill.solid()
        cell.fill.fore_color.rgb = _rgb(theme, "kpi_bg", "#F1F5F9")
    # Data rows with top-3 highlight
    for ri, row in enumerate(top_rows, start=1):
        for ci, c in enumerate(cols):
            v = row.get(c, "")
            sv = "" if v is None else str(v)
            if len(sv) > 60:
                sv = sv[:60] + "…"
            cell = table.cell(ri, ci)
            cell.text = sv
            for p in cell.text_frame.paragraphs:
                for r in p.runs:
                    r.font.name = _font_for(r.text, "body")
                    r.font.size = Pt(CAPTION_PT)
                    r.font.color.rgb = _rgb(theme, "text", "#0F172A")
            if ri <= 3:
                # Top-3 highlight — theme accent @ 12% alpha equivalent
                cell.fill.solid()
                cell.fill.fore_color.rgb = _rgb(theme, "finding_bg", "#F5F3FF")
            elif ri % 2 == 0:
                cell.fill.solid()
                cell.fill.fore_color.rgb = _rgb(theme, "band_bg", "#F8FAFC")


