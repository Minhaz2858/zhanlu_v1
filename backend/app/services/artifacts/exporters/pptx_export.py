def _add_cover_slide(prs, layout, payload: ReportCardPayload, ctx: ExportContext,
                     theme: DeckTheme, recipe: RecipeTokens) -> None:
    s = prs.slides.add_slide(layout)
    _set_bg(s, theme.slide_bg)

    # Optional seeded generative cover background (Phase 4).  A subtle,
    # reproducible flow-field PNG sits behind the stripe + title.  Opt-in
    # via ExportContext.cover_art; decorative, so never breaks the render.
    if getattr(ctx, "cover_art", False):
        try:
            from app.services.artifacts.exporters._advanced import generate_cover_background
            png = generate_cover_background(theme.primary_hex, payload.title or "zhanlu")
            pic = s.shapes.add_picture(io.BytesIO(png), 0, 0,
                                       prs.slide_width, prs.slide_height)
            _send_to_back(s, pic)
        except Exception:
            pass

    # Brand stripe at the top
    _add_rect(s, 0, 0, prs.slide_width, Inches(0.18), fill=theme.primary)

    # Big title
    _add_textbox(
        s, Inches(0.6), Inches(2.3), Inches(12.1), Inches(1.4),
        text=payload.title or "Zhanlu report",
        size=44, bold=True, color=theme.text, align=PP_ALIGN.LEFT,
        font_name=theme.font_heading,
    )
    # Subtitle (source)
    if payload.source:
        _add_textbox(
            s, Inches(0.6), Inches(3.7), Inches(12.1), Inches(0.4),
            text=f"Source: {payload.source}",
            size=16, color=theme.muted, align=PP_ALIGN.LEFT,
            font_name=theme.font_body,
        )
    # Period badge (extracted from title or source)
    period = _extract_period(payload.title) or _extract_period(payload.source or "")
    if period:
        period_y = Inches(4.15)
        if not payload.source:
            period_y = Inches(3.85)
        _add_textbox(
            s, Inches(0.6), period_y, Inches(12.1), Inches(0.35),
            text=f"Period: {period}",
            size=15, color=theme.muted, align=PP_ALIGN.LEFT,
            font_name=theme.font_body,
        )

    # CEO-review badge
    _add_textbox(
        s, Inches(0.6), Inches(6.1), Inches(12.1), Inches(0.35),
        text="Prepared for CEO Review",
        size=13, color=theme.muted, align=PP_ALIGN.LEFT,
        font_name=theme.font_body,
    )

    # Meta strip at the bottom
    meta = f"Generated {short_generated_at(payload)}"
    if ctx.conversation_id:
        meta += f"  ·  conversation {ctx.conversation_id}"
    meta += f"  ·  user_signal: {payload.user_signal or 'default'}"
    _add_textbox(
        s, Inches(0.6), Inches(6.6), Inches(12.1), Inches(0.4),
        text=meta, size=11, color=theme.muted, align=PP_ALIGN.LEFT,
        font_name=theme.font_body,
    )


def _add_agenda_slide(prs, layout, payload: ReportCardPayload,
                      theme: DeckTheme, recipe: RecipeTokens) -> None:
    s = prs.slides.add_slide(layout)
    _set_bg(s, theme.slide_bg)
    _add_section_title(s, "Agenda", theme)
    sections = payload.sections[:10]
    n = len(sections)
    if n <= 3:
        # vertical list (MiniMax: <=3 sections -> list)
        top = Inches(1.7)
        for i, sec in enumerate(sections, start=1):
            _add_textbox(
                s, Inches(0.8), top, Inches(11.9), Inches(0.5),
                text=f"{i}. {sec.title}",
                size=18, color=theme.text, font_name=theme.font_body,
            )
            top += Inches(0.55)
    else:
        # 2-column grid (MiniMax: 4-6 sections -> grid)
        col_w = Inches(5.9)
        gap_x = Inches(0.3)
        rows_per_col = (n + 1) // 2
        for i, sec in enumerate(sections):
            col = i // rows_per_col
            row = i % rows_per_col
            left = Inches(0.8) + col * (col_w + gap_x)
            top = Inches(1.7) + row * Inches(0.6)
            _add_textbox(
                s, left, top, col_w, Inches(0.5),
                text=f"{i + 1}. {sec.title}",
                size=18, color=theme.text, font_name=theme.font_body,
            )


def _add_summary_slide(prs, layout, payload: ReportCardPayload,
                       theme: DeckTheme, recipe: RecipeTokens) -> None:
    s = prs.slides.add_slide(layout)
    _set_bg(s, theme.slide_bg)
    _add_section_title(s, "Executive Summary", theme)

    # --- Headline KPI (first KPI from payload) ---
    cursor = Inches(1.5)
    if payload.kpis:
        headline = payload.kpis[0]
        # Big value
        _add_textbox(
            s, Inches(0.6), cursor, Inches(12.1), Inches(0.9),
            text=str(headline.value or ""), size=56, bold=True,
            color=theme.primary, align=PP_ALIGN.LEFT,
            font_name=theme.font_heading,
        )
        cursor += Inches(0.85)
        # Label + delta on one line
        label_line = headline.label or ""
        if headline.delta:
            label_line += f"  ({headline.delta})"
        if label_line:
            _add_textbox(
                s, Inches(0.6), cursor, Inches(12.1), Inches(0.3),
                text=label_line, size=14, color=theme.muted,
                align=PP_ALIGN.LEFT, font_name=theme.font_body,
            )
            cursor += Inches(0.35)

    # --- Summary text ---
    if payload.summary:
        _add_textbox(
            s, Inches(0.6), cursor, Inches(12.1), Inches(2.2),
            text=payload.summary, size=18, color=theme.text,
            font_name=theme.font_body,
        )
        cursor += Inches(2.3)
    else:
        cursor += Inches(0.2)

    # --- Risk / Opportunity callout boxes (from insights) ---
    risk_insight = None
    opp_insight = None
    for ins in payload.insights or []:
        icon = (ins.icon or "").lower()
        if icon == "trending-down" and not risk_insight:
            risk_insight = ins
        elif icon in ("target", "trending-up", "zap") and not opp_insight:
            opp_insight = ins
        if risk_insight and opp_insight:
            break

    if risk_insight or opp_insight:
        box_h = Inches(1.0)
        gap = Inches(0.25)
        full_w = Inches(12.1)
        half_w = (full_w - gap) / 2
        left_x = Inches(0.6)

        if risk_insight:
            _add_callout_box(
                s, left_x, cursor, half_w, box_h,
                title="Risk", text=risk_insight.text or "",
                bg=RGBColor(0xFE, 0xF2, 0xF2),
                accent=RGBColor(0xDC, 0x26, 0x26),
                theme=theme, recipe=recipe,
            )
        if opp_insight:
            opp_x = left_x + (half_w + gap if risk_insight else Inches(0))
            opp_w = half_w if risk_insight else full_w
            _add_callout_box(
                s, opp_x, cursor, opp_w, box_h,
                title="Opportunity", text=opp_insight.text or "",
                bg=RGBColor(0xF0, 0xFD, 0xF4),
                accent=RGBColor(0x16, 0xA3, 0x4A),
                theme=theme, recipe=recipe,
            )
        cursor += box_h + Inches(0.15)

    # --- Warnings ---
    if payload.warnings:
        box_h = min(Inches(1.6), Inches(7.5) - cursor - Inches(0.3))
        if box_h > Inches(0.4):
            box = _add_rect(s, Inches(0.6), cursor, Inches(12.1), box_h,
                            fill=theme.warn_bg, border=theme.warn_accent,
                            radius_in=recipe.corner_radius_in)
            tf = box.text_frame
            tf.word_wrap = True
            tf.margin_left = Inches(0.2)
            tf.margin_right = Inches(0.2)
            tf.margin_top = Inches(0.1)
            tf.margin_bottom = Inches(0.1)
            p = tf.paragraphs[0]
            p.text = "Warnings"
            p.runs[0].font.size = Pt(16)
            p.runs[0].font.bold = True
            p.runs[0].font.color.rgb = theme.text
            _apply_font(p.runs[0], theme.font_heading)
            for w in payload.warnings:
                p2 = tf.add_paragraph()
                p2.text = f"• {w}"
                p2.runs[0].font.size = Pt(14)
                p2.runs[0].font.color.rgb = theme.text
                _apply_font(p2.runs[0], theme.font_body)


def _add_callout_box(slide, left, top, width, height, *,
                     title: str, text: str,
                     bg: RGBColor, accent: RGBColor,
                     theme: DeckTheme, recipe: RecipeTokens) -> None:
    """Render a titled callout box (Risk / Opportunity)."""
    box = _add_rect(slide, left, top, width, height,
                    fill=bg, border=accent,
                    radius_in=recipe.corner_radius_in)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = Inches(0.15)
    tf.margin_right = Inches(0.15)
    tf.margin_top = Inches(0.1)
    tf.margin_bottom = Inches(0.1)
    p = tf.paragraphs[0]
    p.text = title
    p.runs[0].font.size = Pt(14)
    p.runs[0].font.bold = True
    p.runs[0].font.color.rgb = accent
    _apply_font(p.runs[0], theme.font_heading)
    if text:
        p2 = tf.add_paragraph()
        p2.text = text
        p2.runs[0].font.size = Pt(12)
        p2.runs[0].font.color.rgb = theme.text
        _apply_font(p2.runs[0], theme.font_body)


def _add_kpi_slide(prs, layout, payload: ReportCardPayload,
                   theme: DeckTheme, recipe: RecipeTokens) -> None:
    s = prs.slides.add_slide(layout)
    _set_bg(s, theme.slide_bg)
    _add_section_title(s, "Key Metrics", theme)

    n = len(payload.kpis)

    if n == 1:
        # Hero stat callout (MiniMax stat-callout: a single 60-96pt figure).
        k = payload.kpis[0]
        _add_textbox(
            s, Inches(0.6), Inches(2.1), Inches(12.1), Inches(2.2),
            text=k.value or "\u2014", size=96, bold=True, color=theme.primary,
            font_name=theme.font_heading,
        )
        _add_textbox(
            s, Inches(0.6), Inches(4.4), Inches(12.1), Inches(0.5),
            text=(k.label or "").upper(), size=18, bold=True, color=theme.muted,
            font_name=theme.font_body,
        )
        if k.delta:
            d = k.delta.strip()
            dcolor = (theme.delta_up if d.startswith(("+", "\u25B2"))
                      else theme.delta_down if d.startswith(("-", "\u25BC"))
                      else theme.muted)
            _add_textbox(
                s, Inches(0.6), Inches(5.0), Inches(12.1), Inches(0.5),
                text=k.delta, size=22, bold=True, color=dcolor,
                font_name=theme.font_body,
            )
        if k.caption:
            _add_textbox(
                s, Inches(0.6), Inches(5.6), Inches(12.1), Inches(0.5),
                text=k.caption, size=14, color=theme.muted,
                font_name=theme.font_body,
            )
        return

    # Grid (2x1 / 2x2 / 2x3) for 2-6 KPIs.
    if n == 2:
        ncols, nrows = 2, 1
    elif n <= 4:
        ncols, nrows = 2, 2
    else:
        ncols, nrows = 2, 3   # cap at 6

    cell_w = Inches(5.8)
    cell_h = Inches(2.5)
    gap = Inches(0.2)
    left0 = Inches(0.6)
    top0 = Inches(1.5)

    for idx, k in enumerate(payload.kpis[: ncols * nrows]):
        col = idx % ncols
        row = idx // ncols
        left = left0 + (cell_w + gap) * col
        top = top0 + (cell_h + gap) * row

        box = _add_rect(s, left, top, cell_w, cell_h, fill=theme.kpi_bg,
                        border=theme.border, radius_in=recipe.corner_radius_in)

        tf = box.text_frame
        tf.word_wrap = True
        tf.margin_left = Inches(0.25)
        tf.margin_right = Inches(0.25)
        tf.margin_top = Inches(0.15)
        tf.margin_bottom = Inches(0.15)

        # Label
        p = tf.paragraphs[0]
        p.text = (k.label or "").upper()
        p.runs[0].font.size = Pt(11)
        p.runs[0].font.bold = True
        p.runs[0].font.color.rgb = theme.muted
        _apply_font(p.runs[0], theme.font_body)

        # Value
        p2 = tf.add_paragraph()
        run = p2.add_run()
        run.text = k.value or "—"
        run.font.size = Pt(36)
        run.font.bold = True
        run.font.color.rgb = theme.text
        _apply_font(run, theme.font_heading)

        if k.delta:
            run2 = p2.add_run()
            run2.text = f"   {k.delta}"
            d = k.delta.strip()
            if d.startswith("+") or d.startswith("\u25B2"):
                run2.font.color.rgb = theme.delta_up
            elif d.startswith("-") or d.startswith("\u25BC"):
                run2.font.color.rgb = theme.delta_down
            else:
                run2.font.color.rgb = theme.muted
            run2.font.size = Pt(18)
            run2.font.bold = True
            _apply_font(run2, theme.font_body)

        if k.caption:
            p3 = tf.add_paragraph()
            p3.text = k.caption
            p3.runs[0].font.size = Pt(12)
            p3.runs[0].font.color.rgb = theme.muted
            _apply_font(p3.runs[0], theme.font_body)


def _add_chart_slide(prs, layout, payload: ReportCardPayload,
                     theme: DeckTheme, recipe: RecipeTokens) -> None:
    s = prs.slides.add_slide(layout)
    _set_bg(s, theme.slide_bg)
    _add_section_title(s, payload.chart.title or "Chart", theme)

    rows = chart_rows(payload)
    y_keys = chart_y_keys(payload)
    if not rows or not y_keys:
        return

    # Shared data-prep cap: top-8 categories by value + "Other" bucket.
    x_key = chart_x_key(payload)
    rows = cap_chart_categories(rows, x_key, y_keys)

    chart_type = (payload.chart.type or "bar").lower()
    chart_data = CategoryChartData()
    chart_data.categories = [str(chart_x_value(r, payload)) for r in rows]
    for k in y_keys:
        chart_data.add_series(k, [coerce_number(r.get(k)) or 0 for r in rows])

    x_pos = Inches(0.6)
    y_pos = Inches(1.5)
    cx = Inches(12.1)
    cy = Inches(5.6)

    if chart_type == "line":
        chart_shape = s.shapes.add_chart(
            XL_CHART_TYPE.LINE, x_pos, y_pos, cx, cy, chart_data
        )
    elif chart_type == "pie":
        chart_shape = s.shapes.add_chart(
            XL_CHART_TYPE.PIE, x_pos, y_pos, cx, cy, chart_data
        )
    elif chart_type == "grouped_bar":
        chart_shape = s.shapes.add_chart(
            XL_CHART_TYPE.BAR_CLUSTERED, x_pos, y_pos, cx, cy, chart_data
        )
    elif chart_type == "stacked_bar":
        chart_shape = s.shapes.add_chart(
            XL_CHART_TYPE.BAR_STACKED, x_pos, y_pos, cx, cy, chart_data
        )
    elif chart_type == "stacked_column":
        chart_shape = s.shapes.add_chart(
            XL_CHART_TYPE.COLUMN_STACKED, x_pos, y_pos, cx, cy, chart_data
        )
    elif chart_type == "grouped_column":
        chart_shape = s.shapes.add_chart(
            XL_CHART_TYPE.COLUMN_CLUSTERED, x_pos, y_pos, cx, cy, chart_data
        )
    else:
        chart_shape = s.shapes.add_chart(
            XL_CHART_TYPE.COLUMN_CLUSTERED, x_pos, y_pos, cx, cy, chart_data
        )

    # Accessibility: alt text on the chart (cNvPr@descr) so check_alt_text
    # passes and screen readers can describe the graphic.
    _set_alt_text(chart_shape, f"Chart: {payload.chart.title or payload.chart.type or 'chart'}")

    chart = chart_shape.chart
    chart.has_title = False
    chart.has_legend = True
    if len(y_keys) > 1:
        chart.legend.position = XL_LEGEND_POSITION.BOTTOM
        chart.legend.include_in_layout = False
    else:
        chart.has_legend = False

    # Apply the theme chart palette to every series so the deck's brand
    # colors flow through to the native chart (instead of default blue).
    palette = theme.chart_palette or []
    if palette:
        for i, series in enumerate(chart.series):
            try:
                rgb = _to_rgbcolor(palette[i % len(palette)])
                series.format.fill.solid()
                series.format.fill.fore_color.rgb = rgb
            except Exception:
                # A single series we can't recolor shouldn't break the deck.
                pass

    # Traceability footnote: cite the data source on the headline chart.
    _add_source_footnote(s, payload.source, theme)


