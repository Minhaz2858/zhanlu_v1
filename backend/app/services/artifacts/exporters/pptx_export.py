def _add_data_slide(prs, layout, payload: ReportCardPayload,
                    theme: DeckTheme, recipe: RecipeTokens) -> None:
    s = prs.slides.add_slide(layout)
    _set_bg(s, theme.slide_bg)
    _add_section_title(s, "Data", theme)

    rows = chart_rows(payload)
    if not rows:
        return
    keys = list(rows[0].keys())
    nrows = min(len(rows) + 1, 25)  # header + up to 24 data rows on a slide
    ncols = len(keys)

    table_shape = s.shapes.add_table(
        nrows, ncols, Inches(0.6), Inches(1.5), Inches(12.1), Inches(5.5)
    )
    table = table_shape.table
    # Header row
    for ci, k in enumerate(keys):
        cell = table.cell(0, ci)
        cell.text = k
        for p in cell.text_frame.paragraphs:
            for r in p.runs:
                r.font.size = Pt(11)
                r.font.bold = True
                r.font.color.rgb = theme.text
                _apply_font(r, theme.font_heading)
        _set_cell_bg(cell, theme.band_bg)

    # Data rows (banded)
    for ri, row in enumerate(rows[: nrows - 1], start=1):
        for ci, k in enumerate(keys):
            v = row.get(k, "")
            s_v = "" if v is None else str(v)
            if len(s_v) > 80:
                s_v = s_v[:80] + "…"
            cell = table.cell(ri, ci)
            cell.text = s_v
            for p in cell.text_frame.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(10)
                    r.font.color.rgb = theme.text
                    _apply_font(r, theme.font_body)
            if ri % 2 == 0:
                _set_cell_bg(cell, theme.band_bg)

    if len(rows) > nrows - 1:
        # Combine the truncation note with the source citation when both
        # apply so the bottom-left stays a single traceability line.
        note = f"\u2026 {len(rows) - (nrows - 1)} more rows truncated for slide."
        if (payload.source or "").strip():
            note = f"Source: {payload.source}  \u00b7  {note}"
        _add_textbox(
            s, Inches(0.6), Inches(7.1), Inches(12.1), Inches(0.3),
            text=note, size=10, color=theme.muted, font_name=theme.font_body,
        )
    else:
        _add_source_footnote(s, payload.source, theme)


