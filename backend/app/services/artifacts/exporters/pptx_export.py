def _deck_is_long(payload: ReportCardPayload) -> bool:
    """True when the deck has enough content to warrant section dividers."""
    n = 0
    if payload.sections:
        n += 1
    if payload.summary or payload.warnings:
        n += 1
    if payload.kpis:
        n += 1
    if payload.chart and payload.chart.data:
        n += 1  # chart slide
    if payload.key_findings:
        n += 1
    if payload.insights:
        n += 1
    if payload.recommendations:
        n += 1
    if payload.chart and payload.chart.data:
        n += 1  # data slide
    if payload.methodology:
        n += 1
    return n >= 6


def _add_textbox(slide, left, top, width, height, *,
                 text: str, size: int, bold: bool = False,
                 color=None, align=PP_ALIGN.LEFT,
                 font_name: Optional[str] = None) -> None:
    tb = slide.shapes.add_textbox(left, top, width, height)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = Inches(0)
    tf.margin_right = Inches(0)
