def render(payload: ReportCardPayload, ctx: Optional[ExportContext] = None) -> tuple[bytes, str, str]:
    ctx = ctx or ExportContext()

    # Fully-dynamic path: an explicit ``blocks`` list drives the layout engine
    # (the same engine the Pro deck pipeline uses) instead of the catalog order.
    _raw_blocks = getattr(payload, "blocks", None)
    if _raw_blocks:
        try:
            from app.services.artifacts.document_plan import DocumentPlan
            _plan = DocumentPlan.from_blocks(
                list(_raw_blocks),
                meta={"title": getattr(payload, "title", ""),
                      "theme": getattr(payload, "theme", "")},
            )
            return render_deck(_plan.to_deck_plan(), ctx, rows=[])
        except Exception:
            pass  # fall through to the catalog renderer

    # Resolve the design tokens once and thread them through every builder.
    # Defaults (zhanlu-blue + sharp) reproduce the legacy branded deck; a
    # tenant brand kit (ctx.theme_tokens) takes precedence when set.
    theme = resolve_ctx_theme(ctx)
    recipe = resolve_recipe(ctx.style_recipe)

    prs = Presentation()
    prs.slide_width = Inches(13.333)   # 16:9
    prs.slide_height = Inches(7.5)

    blank_layout = prs.slide_layouts[6]  # blank

    # Build slides in catalog order; each gated on its payload field.
    _add_cover_slide(prs, blank_layout, payload, ctx, theme, recipe)
    if payload.sections:
        _add_agenda_slide(prs, blank_layout, payload, theme, recipe)
    if payload.summary or payload.warnings:
        _add_summary_slide(prs, blank_layout, payload, theme, recipe)
    if payload.kpis:
        _add_kpi_slide(prs, blank_layout, payload, theme, recipe)
    if payload.chart and payload.chart.data:
        _add_chart_slide(prs, blank_layout, payload, theme, recipe)
    # Section divider before the analysis block (findings / insights).
    if (payload.key_findings or payload.insights) and _deck_is_long(payload):
        _add_section_divider(prs, blank_layout, 1, "Analysis", theme, recipe)
    if payload.key_findings:
        _add_key_findings_slide(prs, blank_layout, payload, theme, recipe)
    if payload.insights:
        _add_insights_slide(prs, blank_layout, payload, theme, recipe)
    # Section divider before the actions block (recommendations).
    if payload.recommendations and _deck_is_long(payload):
        _add_section_divider(prs, blank_layout, 2, "Actions", theme, recipe)
    if payload.recommendations:
        _add_recommendations_slide(prs, blank_layout, payload, theme, recipe)
    if payload.chart and payload.chart.data:
        _add_data_slide(prs, blank_layout, payload, theme, recipe)
    if payload.methodology:
        _add_methodology_slide(prs, blank_layout, payload, theme, recipe)
    # NOTE: no "next step" closing slide — payload.next_step is
    # conversational guidance for the in-chat card, not deck content.

    # Footers on every content slide (everything except the cover).
    _add_footers(prs, theme)

    buf = io.BytesIO()
    prs.save(buf)
    return (
        buf.getvalue(),
        "application/vnd.openxmlformats-officedocument.presentationml.presentation",
        ".pptx",
    )


def render_deck(
    plan: Optional[DeckPlan],
    ctx: Optional[ExportContext] = None,
    rows: Optional[list[dict[str, Any]]] = None,
) -> tuple[bytes, str, str]:
    """Render a DeckPlan through the shared layout engine + quality pipeline.

    This is now a thin wrapper over :func:`render_dispatcher.render_pptx_from_plan`
    so the in-process exporter produces byte-identical decks to the sandbox
    renderer (both delegate to ``layout_engine``).  The dispatcher owns the
    audit + deterministic repair + (optional) polish loop.

    When ``plan`` is ``None`` or has no slides, falls back to the catalog
    renderer so callers can use a single entry point.
    """
    ctx = ctx or ExportContext()

    if not plan or not plan.slides:
        return render(
            ReportCardPayload(title=plan.title if plan else "Report"), ctx
        )

    from app.services.artifacts.render_dispatcher import render_pptx_from_plan_sync

    data, _report = render_pptx_from_plan_sync(plan, rows or [], ctx)
    return (
        data,
        "application/vnd.openxmlformats-officedocument.presentationml.presentation",
        ".pptx",
    )


def _build_slide(
    prs, layout, slide: SlidePlan, rows: list[dict[str, Any]],
    section_num: int, ctx: ExportContext, theme: DeckTheme,
    recipe: RecipeTokens,
) -> int:
    """Dispatch one SlidePlan to its layout builder.

    Returns the (possibly incremented) section-number counter so section
    dividers are numbered sequentially across the deck.
    """
    kind = (slide.layout or "").strip().lower().replace("-", "_").replace(" ", "")

    if kind == "cover":
        _add_cover_slide(
            prs, layout, ReportCardPayload(title=slide.title, source=slide.subtitle),
            ctx, theme, recipe,
        )
    elif kind == "agenda":
        _add_agenda_slide(
            prs, layout,
            ReportCardPayload(
                title=slide.title,
                sections=[SectionSpec(title=b) for b in slide.bullets],
            ),
            theme, recipe,
        )
    elif kind == "kpi_grid":
        _add_kpi_slide(
            prs, layout,
            ReportCardPayload(
                title=slide.title,
                kpis=[
                    KPISpec(label=k.label, value=k.value, delta=k.delta, caption=k.caption)
                    for k in slide.kpi_specs
                ],
            ),
            theme, recipe,
        )
    elif kind in ("chart_full", "chart_with_bullets"):
        cs = slide.chart_spec
        chart = ChartSpec(
            type=(cs.chart_type if cs else "bar"),
            title=(cs.title if cs else slide.title),
            x_key=(cs.x_key if cs else ""),
            y_keys=(cs.y_keys if cs else []),
            data=_project_chart_rows(
                rows, cs.x_key if cs else "", cs.y_keys if cs else []
            ),
        )
        _add_chart_slide(
            prs, layout, ReportCardPayload(title=slide.title, chart=chart),
            theme, recipe,
        )
        if kind == "chart_with_bullets" and slide.bullets:
            _add_bullets_slide(prs, layout, slide.title, slide.bullets, theme, recipe)
    elif kind == "findings_cards":
        _add_key_findings_slide(
            prs, layout,
            ReportCardPayload(
                title=slide.title,
                key_findings=[InsightSpec(text=b) for b in slide.bullets],
            ),
            theme, recipe,
        )
    elif kind == "insights_bullets":
        _add_insights_slide(
            prs, layout,
            ReportCardPayload(
                title=slide.title,
                insights=[InsightSpec(text=b) for b in slide.bullets],
            ),
            theme, recipe,
        )
    elif kind == "recommendations":
        _add_recommendations_slide(
            prs, layout,
            ReportCardPayload(
                title=slide.title,
                recommendations=[InsightSpec(text=b) for b in slide.bullets],
            ),
            theme, recipe,
        )
    elif kind == "data_table":
        _add_data_slide(
            prs, layout,
            ReportCardPayload(title=slide.title, chart=ChartSpec(data=rows)),
            theme, recipe,
        )
    elif kind == "methodology":
        _add_methodology_slide(
            prs, layout,
            ReportCardPayload(
                title=slide.title,
                methodology=" ".join(slide.bullets) or slide.subtitle,
            ),
            theme, recipe,
        )
    elif kind == "section_divider":
        section_num += 1
        _add_section_divider(prs, layout, section_num, slide.title, theme, recipe)
    elif kind == "closing":
        _add_closing_slide(prs, layout, slide.title, theme, recipe)
    else:
        # Unknown / future layout: render a generic bullet slide so the deck
        # still renders rather than silently dropping the content.
        _add_bullets_slide(prs, layout, slide.title, slide.bullets or [slide.title],
                           theme, recipe)

    return section_num


def _project_chart_rows(
    rows: list[dict[str, Any]], x_key: str, y_keys: list[str]
) -> list[dict[str, Any]]:
    """Project raw rows down to the chart's x/y columns."""
    if not rows:
        return []
    if not x_key and not y_keys:
        return list(rows)
    out: list[dict[str, Any]] = []
    for r in rows:
        if not isinstance(r, dict):
            continue
        point: dict[str, Any] = {}
        if x_key:
            point[x_key] = r.get(x_key)
        for yk in y_keys:
            point[yk] = r.get(yk)
        if point:
            out.append(point)
    return out


def _add_bullets_slide(prs, layout, title: str, bullets: list[str],
                       theme: DeckTheme, recipe: RecipeTokens) -> None:
    """A generic title + bullets slide (chart_with_bullets, unknown layouts)."""
    s = prs.slides.add_slide(layout)
    _set_bg(s, theme.slide_bg)
    _add_section_title(s, title or "Details", theme)
    top = Inches(1.5)
    for b in bullets[:8]:
        _add_textbox(
            s, Inches(0.6), top, Inches(12.1), Inches(0.6),
            text=f"\u2022  {b}", size=18, color=theme.text,
            font_name=theme.font_body,
        )
        top += Inches(0.65)


def _add_closing_slide(prs, layout, title: str,
                       theme: DeckTheme, recipe: RecipeTokens) -> None:
    """A closing / thank-you slide."""
    s = prs.slides.add_slide(layout)
    _set_bg(s, theme.slide_bg)
    _add_rect(s, 0, 0, prs.slide_width, Inches(0.18), fill=theme.primary)
    _add_textbox(
        s, Inches(0.6), Inches(3.0), Inches(12.1), Inches(1.2),
        text=title or "Thank you", size=48, bold=True, color=theme.text,
        align=PP_ALIGN.CENTER, font_name=theme.font_heading,
    )


