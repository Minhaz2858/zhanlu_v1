"""PPTX export — render a ReportCardPayload as a themed Zhanlu deck.

Uses python-pptx (MIT).  Slide colors come from the vendored
``theme-system`` palettes via :mod:`_theme` (default ``zhanlu-blue``
reproduces the legacy branded deck byte-for-byte).  Slides are emitted
only when their content exists:

  1.  Cover            — brand stripe, title, source, generated-at meta
  2.  Agenda           — numbered list of populated section titles
  3.  Executive Summary— summary paragraph + (optional) warning box
  4.  Key Metrics      — 2x2 / 2x3 KPI tile grid
  5.  Chart            — a native PowerPoint chart (Bar / Line / Pie)
  6.  Key Findings     — finding-accent callout + numbered bullets (<=6)
  7.  Insights         — emoji bullets (<=6)
  8.  Recommendations  — primary-accent callout + numbered bullets (<=6)
  9.  Data             — the chart's data as a banded PowerPoint table
  10. Methodology      — narrative paragraph
  11. Next Step        — closing slide mirroring the cover band

Every content slide (everything except the cover) carries a muted footer
``Generated by Zhanlu AI · N / total``.  The slide aspect is 16:9
(13.333" x 7.5").  All units are EMU (914400 per inch), wrapped in
``Inches()`` / ``Pt()``.
"""

