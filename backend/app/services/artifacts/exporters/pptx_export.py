def _derive_headline(items, fallback: str) -> Optional[str]:
    """One-line takeaway from the first item, or None to keep the label title.

    Used for the assertion-evidence title pattern: the first finding /
    insight / recommendation becomes a big headline and the label
    ("Key Findings") becomes a small eyebrow above it.  Returns None when
    there's no usable text so the caller falls back to the legacy
    label-only title.
    """
    if not items:
        return None
    first = items[0]
    text = getattr(first, "text", None) or (first if isinstance(first, str) else "")
    text = (text or "").strip()
    if not text:
        return None
    if len(text) > 90:
        text = text[:87].rstrip() + "\u2026"
    return text


def _title_block(slide, label: str, theme: DeckTheme,
                 headline: Optional[str] = None) -> float:
    """Draw a content-slide title; return the y (inches) where the body starts.

    Without ``headline``: an H1 label + a 2px accent rule (legacy) — body
    starts at 1.5".  With ``headline``: a small primary eyebrow (the
    label) above a larger assertion headline + accent rule — body starts
    at 2.0".  The label text is always rendered so callers/tests that
    grep for it (e.g. "Key Findings") still match.
    """
    if not headline:
        _add_textbox(
            slide, Inches(0.6), Inches(0.5), Inches(12.1), Inches(0.7),
            text=label, size=28, bold=True, color=theme.text,
            font_name=theme.font_heading,
        )
        _add_rect(slide, Inches(0.6), Inches(1.25), Inches(1.2), Inches(0.05),
                  fill=theme.primary)
        return 1.5
    _add_textbox(
        slide, Inches(0.6), Inches(0.45), Inches(12.1), Inches(0.35),
        text=label, size=13, bold=True, color=theme.primary,
        font_name=theme.font_heading,
    )
    _add_textbox(
        slide, Inches(0.6), Inches(0.8), Inches(12.1), Inches(1.0),
        text=headline, size=30, bold=True, color=theme.text,
        font_name=theme.font_heading,
    )
    _add_rect(slide, Inches(0.6), Inches(1.85), Inches(1.2), Inches(0.05),
              fill=theme.primary)
    return 2.0


