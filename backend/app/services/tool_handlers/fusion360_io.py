# 3. fusion360_make_drawing (backend-side, ezdxf — no Fusion call)
# ---------------------------------------------------------------------------
_SHAPE_TYPES = {"rect", "circle", "line", "polygon"}


def _add_shape(msp, shape, dx=0.0, dy=0.0):
    t = shape.get("type")
    if t == "rect":
        x, y = float(shape.get("x", 0)), float(shape.get("y", 0))
        w, h = float(shape.get("w", 0)), float(shape.get("h", 0))
        msp.add_lwpolyline(
            [(x + dx, y + dy), (x + w + dx, y + dy), (x + w + dx, y + h + dy), (x + dx, y + h + dy)],
            close=True,
        )
    elif t == "circle":
        cx, cy = float(shape.get("cx", 0)) + dx, float(shape.get("cy", 0)) + dy
        msp.add_circle((cx, cy), float(shape.get("r", 1)))
    elif t == "line":
        msp.add_line(
            (float(shape.get("x1", 0)) + dx, float(shape.get("y1", 0)) + dy),
            (float(shape.get("x2", 0)) + dx, float(shape.get("y2", 0)) + dy),
        )
    elif t == "polygon":
        pts = shape.get("points") or []
        msp.add_lwpolyline([(float(p[0]) + dx, float(p[1]) + dy) for p in pts], close=True)


def _add_dim(msp, dim, dx=0.0, dy=0.0):
    p1 = dim.get("p1"); p2 = dim.get("p2")
    if not p1 or not p2:
        return
    x1, y1 = float(p1[0]) + dx, float(p1[1]) + dy
    x2, y2 = float(p2[0]) + dx, float(p2[1]) + dy
    label = str(dim.get("label", ""))
    offset = float(dim.get("offset", 8))
    vx, vy = x2 - x1, y2 - y1
    length = (vx * vx + vy * vy) ** 0.5
    if length < 1e-6:
        return
    nx, ny = -vy / length, vx / length  # unit normal
    # dimension line (offset perpendicular from the p1-p2 segment)
    dl1 = (x1 + nx * offset, y1 + ny * offset)
    dl2 = (x2 + nx * offset, y2 + ny * offset)
    # extension lines
    msp.add_line((x1, y1), dl1)
    msp.add_line((x2, y2), dl2)
    # dimension line with end ticks (short perpendicular marks)
    msp.add_line(dl1, dl2)
    tick = offset * 0.15 + 0.5
    for p, s in ((dl1, 1), (dl2, -1)):
        msp.add_line(p, (p[0] + nx * 0 + (-ny) * tick * s, p[1] + ny * 0 + nx * tick * s))
    # label at midpoint, nudged out along the normal
    mx, my = (dl1[0] + dl2[0]) / 2, (dl1[1] + dl2[1]) / 2
    msp.add_text(label, height=max(2.0, offset * 0.35)).set_placement((mx + nx * 1.5, my + ny * 1.5))


def _fusion360_make_drawing(args: dict, db, user_id: str | None) -> dict:
    spec = args.get("spec")
    if isinstance(spec, str):
        import json as _json
        try:
            spec = _json.loads(spec)
        except Exception:  # noqa: BLE001
            return _bad("spec must be a valid JSON object")
    if not isinstance(spec, dict):
        return _bad("spec (object) is required")

    title = str(spec.get("title") or "Part")
    views = spec.get("views") or []
    dims = spec.get("dims") or []
    if not isinstance(views, list) or not views:
        return _bad("spec.views must be a non-empty list")

    try:
        import ezdxf
    except ImportError:
        return {"success": False, "error": "ezdxf is not installed in the backend.", "retryable": False}

    doc = ezdxf.new("R2010", setup=True)
    msp = doc.modelspace()

    # Arrange views horizontally.
    spacing = 160.0
    view_meta = []
    for i, view in enumerate(views):
        name = str(view.get("name") or f"VIEW {i + 1}")
        dx = i * spacing
        msp.add_text(name, height=5).set_placement((dx, 80))
        for shape in (view.get("shapes") or []):
            _add_shape(msp, shape, dx=dx)
        view_meta.append((name, dx))
        for dim in (view.get("dims") or []):
            _add_dim(msp, dim, dx=dx)
    # global dims (render at the origin / no view offset)
    for dim in dims:
        _add_dim(msp, dim)

    # Title block (bottom-left, modelspace — simple but legible).
    y0 = -90.0
    msp.add_line((-20, y0), (spacing * len(views) - 20, y0))
    msp.add_text(title, height=6).set_placement((-20, y0 - 12))
    msp.add_text(
        f"Units: {spec.get('units', 'mm')}   Scale: 1:1   Date: {datetime.utcnow().strftime('%Y-%m-%d')}   "
        f"Views: {len(views)}",
        height=3.5,
    ).set_placement((-20, y0 - 20))

    import tempfile
    path = tempfile.mktemp(suffix=".dxf")
    doc.saveas(path)
    with open(path, "rb") as f:
        dxf_bytes = f.read()
    try:
        os.remove(path)
    except Exception:  # noqa: BLE001
        pass

    name = (args.get("name") or f"{title.replace(' ', '_')}.dxf").strip()
    if not name.lower().endswith(".dxf"):
        name += ".dxf"
    url, size = _save_file(db, user_id, name, "dxf", dxf_bytes)
    return {
        "success": True,
        "file_url": url,
        "filename": name,
        "size_bytes": size,
        "views": [v[0] for v in view_meta],
    }


