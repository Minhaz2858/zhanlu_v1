"""fusion360_io — geometry exchange + engineering drawing for the CAD Agent.

Three granular tools (all ``fusion360_*``, same pattern as the modeling tools):

- ``fusion360_export_geometry`` — export the live design to STEP/STL/OBJ/IGES/
  SAT/F3D via ``design.exportManager``. The file bytes are returned over the
  socket as base64 (printed by the adsk snippet), decoded here, saved to the
  platform upload dir, and surfaced as a download URL (UserFile row).
- ``fusion360_import_dxf`` — import a 2D DXF (base64) as a sketch onto a
  construction plane via ``app.importManager``, returning the new sketch_index
  so the existing extrude/revolve tools can turn it into a 3D solid.
- ``fusion360_make_drawing`` — generate a dimensioned 2D engineering drawing
  (DXF) from a structured spec the agent builds from the dimensions it already
  knows (its tool-call history). Rendered in the backend with ezdxf — no Fusion
  call needed.

Verified live against Fusion 360 (2026-08-19):
- STEP export: ``design.exportManager.createSTEPExportOptions(path)`` + ``execute``.
- DXF import: ``app.importManager.createDXF2DImportOptions(path, plane)`` +
  ``importToTarget(opts, root)`` (requires the ``planarEntity`` arg — the
  construction plane to place the sketch on).
"""

from __future__ import annotations

import base64
import os
import uuid
from datetime import datetime

from app.config import settings
from app.models.user_file import UserFile
from app.services.tool_registry import registry
from app.services.tool_handlers.fusion360_tool import _call

_PLANES = {
    "xy": "root.xYConstructionPlane",
    "xz": "root.xZConstructionPlane",
    "yz": "root.yZConstructionPlane",
}

# format -> (ExportManager factory suffix, file extension, needs_target)
# Mesh formats (STL/OBJ) tessellate a body/component and need the `root` target as
# the FIRST arg; B-rep formats (STEP/IGES/SAT/F3D) export the design, filename only.
_EXPORT_FORMATS = {
    "step": ("STEP", "step", False),
    "stl": ("STL", "stl", True),
    "obj": ("OBJ", "obj", True),
    "iges": ("IGES", "igs", False),
    "sat": ("SAT", "sat", False),
    "f3d": ("FusionArchive", "f3d", False),
}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _save_file(db, user_id: str | None, name: str, file_type: str, data: bytes) -> tuple[str, int]:
    """Persist generated bytes to the upload dir and return (file_url, size)."""
    ext = os.path.splitext(name)[1] or ("." + file_type)
    unique = uuid.uuid4().hex + ext
    path = settings.upload_path / unique
    path.write_bytes(data)
    url = f"/api/uploads/{unique}"
    try:
        f = UserFile(
            name=name,
            file_type=file_type,
            size=len(data),
            file_url=url,
            source="ai_generated",
            created_by_id=user_id,
        )
        db.add(f)
        db.commit()
    except Exception:  # noqa: BLE001 — file is already on disk; don't fail the tool
        db.rollback()
    return url, len(data)


def _bad(msg: str) -> dict:
    return {"success": False, "error": msg, "retryable": True}


def _get_agent_app(db):
    """Resolve the calling AgentApp via TOOL_CONTEXT_VAR (same pattern as
    fusion_endpoint resolution) so per-agent state never leaks across users."""
    try:
        from app.services.agent_tools import TOOL_CONTEXT_VAR
        app_id = (TOOL_CONTEXT_VAR.get() or {}).get("agent_app_id")
        if app_id and db is not None:
            from app.models.agent_app import AgentApp
            return db.get(AgentApp, app_id)
    except Exception:  # noqa: BLE001
        return None
    return None


def _get_project(db) -> str | None:
    app = _get_agent_app(db)
    if app is not None and isinstance(getattr(app, "tool_config", None), dict):
        return app.tool_config.get("fusion_project")
    return None


def _set_project(db, name: str) -> None:
    app = _get_agent_app(db)
    if app is None:
        return
    tc = dict(app.tool_config or {})
    tc["fusion_project"] = name
    app.tool_config = tc
    try:
        db.add(app)
        db.commit()
    except Exception:  # noqa: BLE001
        db.rollback()


# ---------------------------------------------------------------------------
# 1. fusion360_export_geometry
# ---------------------------------------------------------------------------
def _fusion360_export_geometry(args: dict, db, user_id: str | None) -> dict:
    fmt = (args.get("format") or "step").lower()
    if fmt not in _EXPORT_FORMATS:
        return _bad(f"format must be one of {sorted(_EXPORT_FORMATS)}")
    cls, ext, needs_target = _EXPORT_FORMATS[fmt]
    create_line = (
        f"opts = exp.create{cls}ExportOptions(root, path)\n"
        if needs_target
        else f"opts = exp.create{cls}ExportOptions(path)\n"
    )

    code = (
        "import tempfile, os, base64\n"
        "exp = design.exportManager\n"
        f"path = os.path.join(tempfile.gettempdir(), 'zhanlu_export.{ext}')\n"
        + create_line
        + "ok = exp.execute(opts)\n"
        "if not ok:\n"
        "    print('ZB64_ERR: export returned False')\n"
        "else:\n"
        "    with open(path, 'rb') as f:\n"
        "        print('ZB64:' + base64.b64encode(f.read()).decode())\n"
        "    try: os.remove(path)\n"
        "    except Exception: pass\n"
    )
    r = _call(code, db)
    if r.get("error"):
        return {"success": False, "error": r["error"], "retryable": True}
    out = r.get("result", "") or ""
    if "ZB64_ERR" in out:
        return {"success": False, "error": "Fusion export failed (exportManager returned False).", "retryable": True}
    marker = "ZB64:"
    if marker not in out:
        return {"success": False, "error": "No export data returned from Fusion.", "retryable": True}
    b64 = out.split(marker, 1)[1].strip()
    try:
        data = base64.b64decode(b64)
    except Exception as e:  # noqa: BLE001
        return {"success": False, "error": f"Failed to decode export data: {e}", "retryable": True}

    name = (args.get("name") or f"model.{ext}").strip()
    url, size = _save_file(db, user_id, name, ext, data)
    return {
        "success": True,
        "file_url": url,
        "filename": name,
        "format": fmt,
        "size_bytes": size,
    }


# ---------------------------------------------------------------------------
# 1b. fusion360_save / fusion360_project — named project state
# ---------------------------------------------------------------------------
def _fusion360_save(args: dict, db, user_id: str | None) -> dict:
    """Save the live design as a named .f3d AND remember it as the current project."""
    name = (args.get("name") or "untitled").strip()
    if not name.lower().endswith(".f3d"):
        name += ".f3d"
    r = _fusion360_export_geometry({"format": "f3d", "name": name}, db, user_id)
    if not r.get("success"):
        return r
    _set_project(db, name)
    r["project"] = name
    return r


def _fusion360_project(args: dict, db, user_id: str | None) -> dict:
    """Report the current Fusion project (the filename last saved via fusion360_save)."""
    p = _get_project(db)
    if p:
        return {"success": True, "project": p}
    return {"success": True, "project": None, "note": "No project saved yet."}


# ---------------------------------------------------------------------------
# 2. fusion360_import_dxf
# ---------------------------------------------------------------------------
def _fusion360_import_dxf(args: dict, db, user_id: str | None) -> dict:
    b64 = (args.get("dxf_b64") or "").strip()
    if not b64:
        return _bad("dxf_b64 is required (base64-encoded DXF file content)")
    plane = args.get("plane", "xy")
    if plane not in _PLANES:
        return _bad(f"plane must be one of {sorted(_PLANES)}")
    # strip whitespace/newlines that may have been introduced in transit
    b64 = "".join(b64.split())
    # validate before embedding
    try:
        base64.b64decode(b64)
    except Exception as e:  # noqa: BLE001
        return _bad(f"dxf_b64 is not valid base64: {e}")

    plane_expr = _PLANES[plane]
    code = (
        "import tempfile, os, base64\n"
        "app = adsk.core.Application.get()\n"
        "path = os.path.join(tempfile.gettempdir(), 'zhanlu_import.dxf')\n"
        f"open(path, 'wb').write(base64.b64decode('{b64}'))\n"
        "imp = app.importManager\n"
        f"opts = imp.createDXF2DImportOptions(path, {plane_expr})\n"
        "opts.isSingleSketchResult = True\n"
        "opts.isViewFit = True\n"
        "before = root.sketches.count\n"
        "res = imp.importToTarget(opts, root)\n"
        "try: os.remove(path)\n"
        "except Exception: pass\n"
        "print('IMPORT_OK' if res else 'IMPORT_FAIL', 'SKETCH_INDEX', root.sketches.count - 1, 'BEFORE', before)\n"
    )
    r = _call(code, db)
    if r.get("error"):
        return {"success": False, "error": r["error"], "retryable": True}
    out = r.get("result", "") or ""
    if "IMPORT_FAIL" in out:
        return {"success": False, "error": "Fusion failed to import the DXF.", "retryable": True}
    if "IMPORT_OK" not in out:
        return {"success": False, "error": "Unexpected import result: " + out[:300], "retryable": True}
    # parse SKETCH_INDEX
    idx = None
    if "SKETCH_INDEX" in out:
        try:
            idx = int(out.split("SKETCH_INDEX", 1)[1].strip().split()[0])
        except Exception:  # noqa: BLE001
            idx = None
    return {"success": True, "sketch_index": idx, "plane": plane, "stdout": out.strip()}


