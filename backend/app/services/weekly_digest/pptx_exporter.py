    def _add_markdown_box(self, slide, left, top, width, height, text, *,
                          size=14, color=None, font_name="Inter",
                          base_bold=False) -> None:
        box = slide.shapes.add_textbox(left, top, width, height)
        tf = box.text_frame
        tf.word_wrap = True
        tf.auto_size = MSO_AUTO_SIZE.TEXT_TO_FIT_SHAPE   # auto-shrink if text overflows
        blocks = _markdown_blocks(text)
        first = True
        for blk in blocks:
            para = tf.paragraphs[0] if first else tf.add_paragraph()
            first = False
            if blk["kind"] == "bullet":
                self._add_md_run(para, "• ", size, color, font_name, False)
            elif blk["kind"] == "numbered":
                self._add_md_run(para, f"{blk['num']}. ", size, color, font_name, False)
            heading = blk["kind"] == "heading"
            for txt, bold in blk["runs"]:
                self._add_md_run(para, txt, size, color, font_name,
                                 bold or heading or base_bold)

    def _est_text_height(self, text, size, width_in) -> float:
        """Estimate rendered height of *text* in inches.

        Walks each character through ``_char_width_em`` so CJK
        full-width glyphs consume ~1.0 em instead of the old 0.52
        assumption.  Also accounts for inter-paragraph spacing (6 pt
        after each paragraph except the last).
        """
        if not text:
            return 0.0
        width_pt = width_in * 72.0
        line_h_pt = size * 1.35          # line height (size × 1.35 spacing)
        para_space_pt = 6.0              # default PowerPoint paragraph after-spacing
        blocks = _markdown_blocks(text)
        if not blocks:
            return 0.0
        total_h_pt = 0.0
        for i, blk in enumerate(blocks):
            prefix = "• " if blk["kind"] in ("bullet", "numbered") else ""
            plain = prefix + _block_plain(blk)
            # Walk characters, accumulating em-units per line.
            line_units = 0.0
            lines = 1
            for ch in plain:
                u = _char_width_em(ch) * size  # em-units → pt
                if line_units + u > width_pt:
                    lines += 1
                    line_units = u
                else:
                    line_units += u
            total_h_pt += lines * line_h_pt
            if i < len(blocks) - 1:
                total_h_pt += para_space_pt
        return total_h_pt / 72.0

    def _fit_text(self, text, size, width_in, max_height_in) -> str:
        if self._est_text_height(text, size, width_in) <= max_height_in:
            return text
        sentences = re.split(r"(?<=[。！？!?.;；])", text)
        result = ""
        for sent in sentences:
            candidate = result + sent
            if result and self._est_text_height(candidate, size, width_in) > max_height_in:
                break
            result = candidate
        return (result.rstrip() + "…") if result else text[:40] + "…"

    def _fit_text_size(self, text: str, width_in: float, max_height_in: float,
                       start: int = 11, floor: int = 7):
        """Return ``(full_text, font_size)`` with the largest size in
        ``[floor, start]`` whose estimated height fits ``max_height_in``.

        Unlike :meth:`_fit_text`, this never truncates the text — the full
        string is always returned, so the LLM analysis is never cut off
        mid-sentence.  If even ``floor`` overflows, return it at ``floor`` and
        let ``MSO_AUTO_SIZE.TEXT_TO_FIT_SHAPE`` shrink the last few points.
        """
        if not text:
            return text, start
        size = start
        while size > floor and self._est_text_height(text, size, width_in) > max_height_in:
            size -= 1
        return text, size
