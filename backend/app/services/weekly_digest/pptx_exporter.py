"""Weekly-digest PPTX exporter.

Redesign of :class:`WeeklyDigestPptxBuilder` to match the polished web UI at
``/market-dashboard/weekly-summary``:

* every Chinese run gets an East Asian typeface (``Microsoft YaHei``) via an
  ``<a:ea>`` post-pass, so PowerPoint stops falling back to SimSun/DengXian;
* price charts get compact date labels, thinned category ticks, a fitted
  "nice-step" value axis with ``#,##0`` separators, and clean lines;
* LLM markdown (``**bold**``, ``- `` bullets, ``1. `` lists) renders as
  structured paragraphs instead of a stripped wall of text;
* the product slide gets 3 KPI chips (现价 / 7日变动 / 预测区间), a stacked
  no-overlap analysis column, a styled forecast table and horizontal range
  bars; 涨=red / 跌=green (Chinese market convention);
* the deck gains an Agenda, a section divider, a Disclaimer slide and a
  consistent page header.
"""

