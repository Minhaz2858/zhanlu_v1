"""Weekly digest PPTX exporter.

Renders a :class:`WeeklyReportCard` + its :class:`WeeklyReportProduct` rows
into a themed 16:9 ``.pptx`` deck (``zhanlu-blue``).  The slide vocabulary
mirrors the proven artifact pipeline in ``app/services/artifacts/exporters``
and reuses its low-level shape/theme primitives so the digest deck reads as
the same brand as every other Zhanlu artifact.

Slide order (gated on content, matching the on-page report):

  1.  Cover             — brand stripe, bilingual title, week range + meta
  2.  Market Overview   — 2x2 KPI grid (total / priced / up / down) + narrative
  3.  Executive Summary — LLM summary (when present)
  4.  Warning           — ``error_msg`` callout (when present)
  5.  No data           — empty-state slide (when a report has no products)
  6..N Product slide    — per-product price charts + forecast table + analysis

Only ``python-pptx`` is used (already pinned in requirements.txt) — charts are
native PowerPoint ``CategoryChartData`` so they stay editable in the editor.
"""

from __future__ import annotations

import io
from typing import Optional

from pptx import Presentation
from pptx.chart.data import CategoryChartData
from pptx.enum.chart import XL_CHART_TYPE
from pptx.enum.text import PP_ALIGN
from pptx.util import Inches, Pt
from sqlalchemy.orm import Session

from app.models.weekly_digest import WeeklyReportCard, WeeklyReportProduct
from app.services.artifacts.exporters._common import coerce_number
from app.services.artifacts.exporters._theme import DeckTheme, _to_rgbcolor, load_theme
from app.services.artifacts.exporters.pptx_export import (
    _add_footers,
    _add_rect,
    _add_section_title,
    _add_textbox,
    _apply_font,
    _set_alt_text,
    _set_bg,
    _set_cell_bg,
)

FOOTER_TEXT = "Generated by Zhanlu AI"

_SLIDE_W = Inches(13.333)
_SLIDE_H = Inches(7.5)

# Markdown bold markers the LLM emits ("**标题：**") — stripped for slide text.
_MD_BOLD = "**"


def _clean_markdown(text: Optional[str]) -> str:
    """Strip the LLM's Markdown bold markers for plain slide text."""
    if not text:
        return ""
    return (text or "").replace(_MD_BOLD, "").strip()


def _fmt_price(value: Optional[float]) -> str:
    """Format a price scalar as a compact CNY figure (empty when absent)."""
    if value is None:
        return ""
    try:
        return f"{float(value):,.0f}"
    except (TypeError, ValueError):
        return ""


def _fmt_change(value: Optional[float]) -> str:
    """Format a 7-day percent change with an explicit sign."""
    if value is None:
        return ""
    try:
        return f"{float(value):+.2f}%"
    except (TypeError, ValueError):
        return ""


def _fmt_confidence(value) -> str:
    """Format a 0-1 confidence float as a percentage."""
    if value is None:
        return "—"
    try:
        return f"{float(value):.0%}"
    except (TypeError, ValueError):
        return "—"


def _downsample(points: list[dict], max_points: int = 60) -> list[dict]:
    """Evenly thin a price series so the native chart stays readable."""
    if not points or len(points) <= max_points:
        return list(points)
    step = len(points) / max_points
    return [points[int(i * step)] for i in range(max_points)]


class WeeklyDigestPptxBuilder:
    """Render a :class:`WeeklyReportCard` + products into a 16:9 ``.pptx``."""

    def __init__(self, db: Session, theme: Optional[DeckTheme] = None):
        self.db = db
        self.theme = theme or load_theme("zhanlu-blue")
        self._prs: Optional[Presentation] = None
        self._layout = None

    # ── Data loading ──────────────────────────────────────────────────────

    def _load_card(self, report_id: str) -> WeeklyReportCard:
        card = self.db.query(WeeklyReportCard).filter(
            WeeklyReportCard.id == report_id,
            WeeklyReportCard.is_deleted == False,  # noqa: E712
        ).first()
        if card is None:
            raise LookupError(f"WeeklyReportCard not found: {report_id}")
        return card

    def _load_products(self, report_id: str) -> list[WeeklyReportProduct]:
        return self.db.query(WeeklyReportProduct).filter(
            WeeklyReportProduct.report_id == report_id,
            WeeklyReportProduct.is_deleted == False,  # noqa: E712
        ).order_by(WeeklyReportProduct.report_order).all()

    # ── Entry point ───────────────────────────────────────────────────────

    def build(self, report_id: str) -> io.BytesIO:
        """Load the report and emit the full deck into a ``BytesIO``."""
        card = self._load_card(report_id)
        products = self._load_products(report_id)

        prs = Presentation()
        prs.slide_width = _SLIDE_W
        prs.slide_height = _SLIDE_H
        self._prs = prs
        self._layout = prs.slide_layouts[6]  # blank

        self._add_cover(card)
        self._add_market_overview(card, products)
        if card.executive_summary:
            self._add_executive_summary(card)
        if card.error_msg:
            self._add_warning_slide(card)
        if not products:
            self._add_no_data_slide(card)
        else:
            for p in products:
                self._add_product_slide(card, p)

        _add_footers(prs, self.theme)

        buf = io.BytesIO()
        prs.save(buf)
        buf.seek(0)
        return buf

    # ── Slide builders ────────────────────────────────────────────────────

    def _add_cover(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)

        # Brand stripe at the top
        _add_rect(s, 0, 0, _SLIDE_W, Inches(0.18), fill=t.primary)

        # Bilingual title: Chinese on top, English subtitle below.
        _add_textbox(
            s, Inches(0.6), Inches(2.3), Inches(12.1), Inches(1.4),
            text=card.title_zh or "周度总结及预测",
            size=44, bold=True, color=t.text, align=PP_ALIGN.LEFT,
            font_name=t.font_heading,
        )
        if card.title_en:
            _add_textbox(
                s, Inches(0.6), Inches(3.7), Inches(12.1), Inches(0.5),
                text=card.title_en, size=18, color=t.muted, align=PP_ALIGN.LEFT,
                font_name=t.font_body,
            )

        # Week range meta strip at the bottom.
        week_txt = self._week_range_text(card)
        meta = week_txt
        if card.generated_at:
            meta += f"  ·  生成时间 {card.generated_at.strftime('%Y-%m-%d %H:%M')}"
        _add_textbox(
            s, Inches(0.6), Inches(6.6), Inches(12.1), Inches(0.4),
            text=meta, size=12, color=t.muted, align=PP_ALIGN.LEFT,
            font_name=t.font_body,
        )

    def _add_market_overview(
        self, card: WeeklyReportCard, products: list[WeeklyReportProduct]
    ) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "市场概况 / Market Overview", t)

        priced = [p for p in products if p.current_price is not None]
        up = sum(1 for p in priced if (p.change_pct_7d or 0) > 0)
        down = sum(1 for p in priced if (p.change_pct_7d or 0) < 0)
        kpis = [
            ("品种总数", str(len(products)), None),
            ("已定价", str(len(priced)), None),
            ("上涨", str(up), None),
            ("下跌", str(down), None),
        ]

        cell_w = Inches(5.8)
        cell_h = Inches(1.6)
        gap = Inches(0.2)
        left0 = Inches(0.6)
        top0 = Inches(1.5)
        for idx, (label, value, _delta) in enumerate(kpis):
            col = idx % 2
            row = idx // 2
            left = left0 + (cell_w + gap) * col
            top = top0 + (cell_h + gap) * row
            box = _add_rect(s, left, top, cell_w, cell_h,
                            fill=t.kpi_bg, border=t.border, radius_in=0.08)
            tf = box.text_frame
            tf.word_wrap = True
            tf.margin_left = Inches(0.25)
            tf.margin_right = Inches(0.25)
            tf.margin_top = Inches(0.15)
            tf.margin_bottom = Inches(0.15)
            p = tf.paragraphs[0]
            p.text = label
            p.runs[0].font.size = Pt(11)
            p.runs[0].font.bold = True
            p.runs[0].font.color.rgb = t.muted
            _apply_font(p.runs[0], t.font_body)
            p2 = tf.add_paragraph()
            run = p2.add_run()
            run.text = value
            run.font.size = Pt(30)
            run.font.bold = True
            run.font.color.rgb = t.text
            _apply_font(run, t.font_heading)

        if card.market_overview:
            _add_textbox(
                s, Inches(0.6), Inches(5.1), Inches(12.1), Inches(1.9),
                text=_clean_markdown(card.market_overview)[:600],
                size=12, color=t.text, font_name=t.font_body,
            )

    def _add_executive_summary(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "总结预测及建议 / Executive Summary", t)
        _add_textbox(
            s, Inches(0.6), Inches(1.5), Inches(12.1), Inches(5.4),
            text=_clean_markdown(card.executive_summary)[:1200],
            size=15, color=t.text, font_name=t.font_body,
        )

    def _add_warning_slide(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "生成告警 / Warnings", t)
        box = _add_rect(s, Inches(0.6), Inches(1.5), Inches(12.1), Inches(3.0),
                        fill=t.warn_bg, border=t.warn_accent, radius_in=0.08)
        tf = box.text_frame
        tf.word_wrap = True
        tf.margin_left = Inches(0.25)
        tf.margin_right = Inches(0.25)
        tf.margin_top = Inches(0.2)
        tf.margin_bottom = Inches(0.2)
        p = tf.paragraphs[0]
        p.text = card.error_msg or ""
        p.runs[0].font.size = Pt(14)
        p.runs[0].font.color.rgb = t.text
        _apply_font(p.runs[0], t.font_body)

    def _add_no_data_slide(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "产品数据", t)
        _add_textbox(
            s, Inches(0.6), Inches(3.0), Inches(12.1), Inches(1.2),
            text="本报告暂无产品数据。", size=20, bold=True, color=t.muted,
            align=PP_ALIGN.CENTER, font_name=t.font_body,
        )

    def _add_product_slide(
        self, card: WeeklyReportCard, p: WeeklyReportProduct
    ) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)

        # Title band: product name (zh + en) on the left, price badges right.
        _add_textbox(
            s, Inches(0.6), Inches(0.4), Inches(8.0), Inches(0.7),
            text=p.product_name_zh or p.product_key, size=24, bold=True,
            color=t.text, font_name=t.font_heading,
        )
        if p.product_name_en:
            _add_textbox(
                s, Inches(0.6), Inches(1.05), Inches(8.0), Inches(0.35),
                text=p.product_name_en, size=12, color=t.muted,
                font_name=t.font_body,
            )
        _add_rect(s, Inches(0.6), Inches(1.45), Inches(1.2), Inches(0.04),
                  fill=t.primary)

        # KPI badges (top-right).
        badge_text = f"现价 {_fmt_price(p.current_price)} 元/吨"
        if p.change_pct_7d is not None:
            badge_text += f"   |   {_fmt_change(p.change_pct_7d)}"
        chg_color = t.muted
        if (p.change_pct_7d or 0) > 0:
            chg_color = t.delta_up
        elif (p.change_pct_7d or 0) < 0:
            chg_color = t.delta_down
        _add_textbox(
            s, Inches(8.2), Inches(0.55), Inches(4.5), Inches(0.6),
            text=badge_text, size=14, bold=True, color=chg_color,
            align=PP_ALIGN.RIGHT, font_name=t.font_body,
        )

        # Two price charts side by side (12mo left, 30d right).
        chart_top = Inches(1.7)
        chart_h = Inches(2.6)
        chart_w = Inches(5.95)
        self._add_price_chart(s, "近12个月价格走势", p.price_12mo, max_points=60,
                              left=Inches(0.6), top=chart_top,
                              width=chart_w, height=chart_h)
        self._add_price_chart(s, "近30日价格走势", p.price_30d, max_points=30,
                              left=Inches(6.75), top=chart_top,
                              width=chart_w, height=chart_h)

        # Forecast table below the charts.
        self._add_forecast_table(s, p, Inches(0.6), Inches(4.5),
                                 Inches(5.95), Inches(2.0))

        # Analysis text: market analysis + AI decision (right column).
        body_left = Inches(6.75)
        body_top = Inches(4.5)
        _add_textbox(
            s, body_left, body_top, Inches(5.95), Inches(0.3),
            text="市场分析", size=13, bold=True, color=t.primary,
            font_name=t.font_heading,
        )
        _add_textbox(
            s, body_left, body_top + Inches(0.32), Inches(5.95), Inches(1.3),
            text=_clean_markdown(p.market_analysis)[:360],
            size=10, color=t.text, font_name=t.font_body,
        )
        _add_textbox(
            s, body_left, Inches(5.85), Inches(5.95), Inches(0.3),
            text="AI 决策", size=13, bold=True, color=t.primary,
            font_name=t.font_heading,
        )
        _add_textbox(
            s, body_left, Inches(6.17), Inches(5.95), Inches(0.95),
            text=_clean_markdown(p.ai_decision)[:280],
            size=10, color=t.text, font_name=t.font_body,
        )

    # ── Product sub-components ────────────────────────────────────────────

    def _add_price_chart(
        self, slide, title: str, points: Optional[list], max_points: int,
        left, top, width, height,
    ) -> None:
        t = self.theme
        if not points:
            _add_textbox(
                slide, left, top, width, height,
                text=f"{title}\n（暂无数据）", size=12, color=t.muted,
                align=PP_ALIGN.CENTER, font_name=t.font_body,
            )
            return

        rows = _downsample(list(points), max_points)
        chart_data = CategoryChartData()
        chart_data.categories = [str(r.get("date", "")) for r in rows]
        chart_data.add_series(
            "价格", [coerce_number(r.get("price")) or 0 for r in rows]
        )

        shape = slide.shapes.add_chart(
            XL_CHART_TYPE.LINE, left, top, width, height, chart_data
        )
        _set_alt_text(shape, f"Chart: {title}")
        chart = shape.chart
        chart.has_title = True
        chart.chart_title.text_frame.text = title
        chart.chart_title.text_frame.paragraphs[0].runs[0].font.size = Pt(11)
        chart.has_legend = False

        palette = t.chart_palette or []
        for i, series in enumerate(chart.series):
            try:
                rgb = _to_rgbcolor(palette[i % len(palette)])
                series.format.fill.solid()
                series.format.fill.fore_color.rgb = rgb
            except Exception:
                pass

    def _add_forecast_table(
        self, slide, p: WeeklyReportProduct,
        left, top, width, height,
    ) -> None:
        t = self.theme
        _add_textbox(
            slide, left, top, width, Inches(0.3),
            text="预测", size=13, bold=True, color=t.primary,
            font_name=t.font_heading,
        )

        headers = ["周期", "基准", "看涨", "看跌", "置信度"]
        rows = []
        for horizon, key in (("7天", "forecast_7d"), ("30天", "forecast_30d")):
            payload = getattr(p, key, None) or {}
            rows.append([
                horizon,
                _fmt_price(payload.get("base")),
                _fmt_price(payload.get("bull")),
                _fmt_price(payload.get("bear")),
                _fmt_confidence(payload.get("confidence")),
            ])

        table_shape = slide.shapes.add_table(
            len(rows) + 1, len(headers), left, top + Inches(0.35),
            width, Inches(1.4)
        )
        table = table_shape.table

        for ci, h in enumerate(headers):
            cell = table.cell(0, ci)
            cell.text = h
            for para in cell.text_frame.paragraphs:
                for r in para.runs:
                    r.font.size = Pt(10)
                    r.font.bold = True
                    r.font.color.rgb = t.text
                    _apply_font(r, t.font_heading)
            _set_cell_bg(cell, t.band_bg)

        for ri, row in enumerate(rows, start=1):
            for ci, v in enumerate(row):
                cell = table.cell(ri, ci)
                cell.text = v
                for para in cell.text_frame.paragraphs:
                    for r in para.runs:
                        r.font.size = Pt(10)
                        r.font.color.rgb = t.text
                        _apply_font(r, t.font_body)

    # ── Helpers ───────────────────────────────────────────────────────────

    @staticmethod
    def _week_range_text(card: WeeklyReportCard) -> str:
        try:
            return f"{card.week_start.isoformat()} ~ {card.week_end.isoformat()}"
        except AttributeError:
            return ""
