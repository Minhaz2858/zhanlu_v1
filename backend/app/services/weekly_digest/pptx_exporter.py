# ── Formatting helpers ─────────────────────────────────────────────────────

def _fmt_price(value: Optional[float]) -> str:
    if value is None:
        return "N/A"
    try:
        return f"{float(value):,.0f}"
    except (TypeError, ValueError):
        return "N/A"


def _fmt_change(value: Optional[float]) -> str:
    if value is None:
        return "N/A"
    try:
        v = float(value)
        return f"{v:+.2f}%"
    except (TypeError, ValueError):
        return "N/A"


def _fmt_confidence(value) -> str:
    if value is None:
        return "—"
    try:
        return f"{float(value):.0%}"
    except (TypeError, ValueError):
        return "—"


def _downsample(points: list[dict], max_points: int = 60) -> list[dict]:
    if not points or len(points) <= max_points:
        return list(points)
    step = len(points) / max_points
    return [points[int(i * step)] for i in range(max_points)]


# ── Markdown parsing ───────────────────────────────────────────────────────

def _parse_inline_bold(text: str) -> list[tuple[str, bool]]:
    parts = (text or "").split("**")
    runs: list[tuple[str, bool]] = []
    for i, part in enumerate(parts):
        if part == "":
            continue
        runs.append((part, i % 2 == 1))
    return runs


def _markdown_blocks(text: Optional[str]) -> list[dict]:
    blocks: list[dict] = []
    if not text:
        return blocks
    for raw in str(text).splitlines():
        line = raw.strip()
        if not line:
            continue
        m = re.match(r"^(\d+)[.)、]\s*(.*)$", line)
        if m:
            blocks.append({"kind": "numbered", "num": m.group(1),
                           "runs": _parse_inline_bold(m.group(2))})
            continue
        if line.startswith(("- ", "* ", "• ")):
            blocks.append({"kind": "bullet",
                           "runs": _parse_inline_bold(line[2:].strip())})
            continue
        m2 = re.match(r"^#{1,6}\s+(.*)$", line)
        if m2:
            blocks.append({"kind": "heading",
                           "runs": _parse_inline_bold(m2.group(1))})
            continue
        blocks.append({"kind": "paragraph", "runs": _parse_inline_bold(line)})
    return blocks


def _block_plain(block: dict) -> str:
    return "".join(t for t, _ in block["runs"])


def _char_width_em(ch: str) -> float:
    """Return the width of *ch* in em-units relative to font size.

    CJK ideographs and fullwidth forms are ~1.0 em; narrow/Latin
    chars are ~0.5 em.  Used by ``_est_text_height`` to produce
    accurate line-count estimates for mixed CJK/Latin text.
    """
    if not ch.strip():
        return 0.5
    eaw = unicodedata.east_asian_width(ch)
    if eaw in ("W", "F"):          # Wide / Fullwidth
        return 1.0
    if eaw == "A":                  # Ambiguous — treat as half in CJK context
        return 0.55
    return 0.5                      # NaRrow / Latin / digit / punctuation


# ── Axis / label math ──────────────────────────────────────────────────────

def _nice_number(x: float) -> float:
    if x <= 0:
        return 1.0
    exp = math.floor(math.log10(x))
    f = x / (10 ** exp)
    if f < 1.5:
        nf = 1.0
    elif f < 2.5:
        nf = 2.0
    elif f < 4.0:
        nf = 2.5
    elif f < 7.5:
        nf = 5.0
    else:
        nf = 10.0
    return nf * (10 ** exp)


def _nice_axis_range(vmin: float, vmax: float, target_ticks: int = 6) -> tuple[float, float, float]:
    vmin = float(vmin)
    vmax = float(vmax)
    if vmin == vmax:
        if vmin == 0:
            return 0.0, 1.0, 0.2
        pad = abs(vmin) * 0.1 or 1.0
        vmin -= pad
        vmax += pad
    raw = (vmax - vmin) / target_ticks
    step = _nice_number(raw)
    axis_min = math.floor(vmin / step) * step
    axis_max = math.ceil(vmax / step) * step
    if axis_min >= axis_max:
        axis_max = axis_min + step
    return axis_min, axis_max, step


def _short_date_label(datestr: str, mode: str) -> str:
    s = (datestr or "").strip()
    parts = s.split("-")
    if mode == "month":
        if len(parts) >= 2:
            return f"{parts[1].lstrip('0')}月"
        return s
    # "day" mode -> MM-DD
    if len(parts) >= 3:
        return f"{parts[1]}-{parts[2]}"
    return s


# ── CJK font helpers ───────────────────────────────────────────────────────

def _set_east_asian_typeface(run, typeface: str) -> None:
    try:
        rPr = run._r.get_or_add_rPr()
        for el in rPr.findall(qn("a:ea")):
            rPr.remove(el)
        ea = rPr.makeelement(qn("a:ea"), {"typeface": typeface})
        latin = rPr.find(qn("a:latin"))
        if latin is not None:
            latin.addnext(ea)
            return
        cs = rPr.find(qn("a:cs"))
        if cs is not None:
            cs.addprevious(ea)
            return
        rPr.append(ea)
    except Exception:
        pass


def _apply_cjk_to_text_frame(tf, typeface: str) -> None:
    for para in tf.paragraphs:
        for run in para.runs:
            _set_east_asian_typeface(run, typeface)


def _apply_cjk_to_slide(slide, typeface: str) -> None:
    for shape in slide.shapes:
        if getattr(shape, "has_text_frame", False):
            try:
                _apply_cjk_to_text_frame(shape.text_frame, typeface)
            except Exception:
                pass
        if getattr(shape, "has_table", False):
            try:
                for row in shape.table.rows:
                    for cell in row.cells:
                        _apply_cjk_to_text_frame(cell.text_frame, typeface)
            except Exception:
                pass
        if getattr(shape, "has_chart", False):
            try:
                chart = shape.chart
                if chart.has_title:
                    _apply_cjk_to_text_frame(chart.chart_title.text_frame, typeface)
            except Exception:
                pass


class WeeklyDigestPptxBuilder:
    """Render a :class:`WeeklyReportCard` + products into a 16:9 ``.pptx``."""

    def __init__(self, db: Session, theme: Optional[DeckTheme] = None):
        self.db = db
        self.theme = theme or load_theme("zhanlu-blue")
        self._prs: Optional[Presentation] = None
        self._layout = None

    # ── Data loading ──────────────────────────────────────────────────────

    def _load_card(self, report_id: str) -> WeeklyReportCard:
        card = self.db.query(WeeklyReportCard).filter(
            WeeklyReportCard.id == report_id,
            WeeklyReportCard.is_deleted == False,  # noqa: E712
        ).first()
        if card is None:
            raise LookupError(f"WeeklyReportCard not found: {report_id}")
        return card

    def _load_products(self, report_id: str) -> list[WeeklyReportProduct]:
        return self.db.query(WeeklyReportProduct).filter(
            WeeklyReportProduct.report_id == report_id,
            WeeklyReportProduct.is_deleted == False,  # noqa: E712
        ).order_by(WeeklyReportProduct.report_order).all()

    # ── Entry point ───────────────────────────────────────────────────────

    def build(self, report_id: str) -> io.BytesIO:
        card = self._load_card(report_id)
        products = self._load_products(report_id)

        prs = Presentation()
        prs.slide_width = _SLIDE_W
        prs.slide_height = _SLIDE_H
        self._prs = prs
        self._layout = prs.slide_layouts[6]  # blank

        self._add_cover(card)
        self._add_market_overview(card, products)
        if card.executive_summary:
            self._add_executive_summary(card)

        divider_idx: Optional[int] = None
        if products:
            self._add_agenda(products)
            self._add_section_divider()
            divider_idx = len(prs.slides._sldIdLst)  # 1-based index of divider
            total = len(products)
            for idx, p in enumerate(products, start=1):
                self._add_product_slide(card, p, idx, total)
        else:
            self._add_no_data_slide(card)

        if card.error_msg:
            self._add_warning_slide(card)
        self._add_disclaimer(card)

        # CJK post-pass across every slide.
        cjk = self.theme.font_cjk or "Microsoft YaHei"
        for s in prs.slides:
            _apply_cjk_to_slide(s, cjk)

        self._add_page_header(prs, card, {divider_idx} if divider_idx else set())
        _add_footers(prs, self.theme)

        buf = io.BytesIO()
        prs.save(buf)
        buf.seek(0)
        return buf

    # ── Shared chrome ─────────────────────────────────────────────────────

    def _add_page_header(self, prs, card, skip_indices) -> None:
        t = self.theme
        title = (card.title_zh or "").strip()
        if not title:
            return
        for i, slide in enumerate(prs.slides, start=1):
            if i == 1 or i in skip_indices:
                continue
            _add_textbox(
                slide, Inches(9.0), Inches(0.12), Inches(3.7), Inches(0.3),
                text=title, size=9, color=t.muted, align=PP_ALIGN.RIGHT,
                font_name=t.font_body,
            )

    # ── Slide builders ────────────────────────────────────────────────────

    def _add_cover(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_rect(s, 0, 0, Inches(0.35), _SLIDE_H, fill=t.primary)
        _add_rect(s, Inches(0.35), 0, Inches(12.98), Inches(0.18), fill=t.primary)

        _add_textbox(
            s, Inches(1.2), Inches(1.5), Inches(11), Inches(0.4),
            text="市场周报 · MARKET WEEKLY", size=13, bold=True,
            color=t.primary, font_name=t.font_heading,
        )
        _add_textbox(
            s, Inches(1.2), Inches(2.0), Inches(11.5), Inches(1.3),
            text=card.title_zh or "周度总结及预测", size=48, bold=True,
            color=t.primary_dark, font_name=t.font_heading,
        )
        _add_textbox(
            s, Inches(1.2), Inches(3.3), Inches(11.5), Inches(0.5),
            text=card.title_en or "Weekly Summary & Forecast", size=18,
            color=t.muted, font_name=t.font_body,
        )
        _add_rect(s, Inches(1.25), Inches(3.95), Inches(2.2), Inches(0.06),
                  fill=t.primary)

        week = self._week_range_text(card)
        _add_textbox(
            s, Inches(1.2), Inches(4.5), Inches(8), Inches(0.4),
            text=f"报告周期：{week or '—'}", size=13, color=t.text,
            font_name=t.font_body,
        )
        _add_textbox(
            s, Inches(1.2), Inches(5.0), Inches(8), Inches(0.4),
            text=f"覆盖品种：{card.product_count or 0} 个", size=13,
            color=t.text, font_name=t.font_body,
        )

    def _add_market_overview(self, card: WeeklyReportCard, products: list) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "市场概况 / Market Overview", t)
        _add_textbox(
            s, Inches(0.6), Inches(1.4), Inches(12.1), Inches(0.7),
            text=card.market_overview or "", size=14, color=t.text,
            font_name=t.font_body,
        )

        up = sum(1 for p in products if (p.change_pct_7d or 0) > 0)
        down = sum(1 for p in products if (p.change_pct_7d or 0) < 0)
        priced = sum(1 for p in products if p.current_price is not None)
        tiles = [
            ("品种总数", str(len(products)), t.primary),
            ("已定价", str(priced), t.primary),
            ("上涨", str(up), _UP_COLOR),
            ("下跌", str(down), _DOWN_COLOR),
        ]
        tile_w = Inches(2.85)
        gap = Inches(0.2)
        y = Inches(2.5)
        for i, (label, val, color) in enumerate(tiles):
            x = Inches(0.6) + i * (tile_w + gap)
            box = _add_rect(s, x, y, tile_w, Inches(1.5), fill=t.band_bg,
                            border=t.border, radius_in=0.08)
            tf = box.text_frame
            tf.word_wrap = True
            p1 = tf.paragraphs[0]
            r1 = p1.add_run()
            r1.text = val
            r1.font.size = Pt(34)
            r1.font.bold = True
            r1.font.color.rgb = color
            r1.font.name = t.font_body
            p2 = tf.add_paragraph()
            r2 = p2.add_run()
            r2.text = label
            r2.font.size = Pt(12)
            r2.font.bold = True
            r2.font.color.rgb = t.muted
            r2.font.name = t.font_body

    def _add_executive_summary(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "执行摘要 / Executive Summary", t)
        self._add_markdown_box(
            s, Inches(0.6), Inches(1.6), Inches(12.1), Inches(4.6),
            card.executive_summary or "", size=15, color=t.text,
            font_name=t.font_body,
        )

    def _add_agenda(self, products: list) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "目录 / Agenda", t)
        y = Inches(1.7)
        for i, p in enumerate(products, start=1):
            label = f"{i:02d}   {p.product_name_zh or p.product_key}"
            _add_textbox(
                s, Inches(0.9), y, Inches(9), Inches(0.5),
                text=label, size=16, bold=True, color=t.text,
                font_name=t.font_heading,
            )
            y += Inches(0.55)

    def _add_section_divider(self) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.primary_dark)
        _add_textbox(
            s, Inches(0.9), Inches(3.0), Inches(11), Inches(1.0),
            text="产品明细", size=40, bold=True, color=_to_rgbcolor("#ffffff"),
            font_name=t.font_heading,
        )
        _add_textbox(
            s, Inches(0.9), Inches(4.1), Inches(11), Inches(0.5),
            text="Product Detail", size=16, color=_to_rgbcolor("#bfdbfe"),
            font_name=t.font_body,
        )

    def _add_disclaimer(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "免责声明 / Disclaimer", t)
        _add_textbox(
            s, Inches(0.6), Inches(1.9), Inches(12.1), Inches(1.2),
            text=DISCLAIMER_TEXT, size=14, color=t.muted,
            font_name=t.font_body,
        )

    def _add_warning_slide(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "告警 / Warning", t)
        _add_rect(s, Inches(0.6), Inches(1.6), Inches(12.1), Inches(1.4),
                  fill=t.warn_bg, border=t.warn_accent, radius_in=0.08)
        _add_textbox(
            s, Inches(0.9), Inches(1.95), Inches(11.5), Inches(0.9),
            text=card.error_msg or "", size=14, color=t.text,
            font_name=t.font_body,
        )

    def _add_no_data_slide(self, card: WeeklyReportCard) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)
        _add_section_title(s, "产品明细 / Product Detail", t)
        _add_textbox(
            s, Inches(0.6), Inches(2.4), Inches(12.1), Inches(1.0),
            text="暂无产品数据", size=20, color=t.muted, align=PP_ALIGN.CENTER,
            font_name=t.font_body,
        )

    # ── Helpers ───────────────────────────────────────────────────────────

    @staticmethod
    def _week_range_text(card: WeeklyReportCard) -> str:
        try:
            return f"{card.week_start.isoformat()} ~ {card.week_end.isoformat()}"
        except AttributeError:
            return ""

    def _add_product_slide(self, card: WeeklyReportCard, p: WeeklyReportProduct,
                           idx: int, total: int) -> None:
        t = self.theme
        s = self._prs.slides.add_slide(self._layout)
        _set_bg(s, t.slide_bg)

        name_zh = p.product_name_zh or p.product_key or ""
        name_en = p.product_name_en or ""
        _add_textbox(s, Inches(0.6), Inches(0.4), Inches(7.3), Inches(0.55),
                     text=name_zh, size=24, bold=True, color=t.primary_dark,
                     font_name=t.font_heading)
        if name_en:
            _add_textbox(s, Inches(0.6), Inches(0.98), Inches(7.3), Inches(0.3),
                         text=name_en, size=12, color=t.muted,
                         font_name=t.font_body)
        _add_rect(s, Inches(0.6), Inches(1.38), Inches(1.2), Inches(0.05),
                  fill=t.primary)

        self._add_kpi_chips(s, p)

        # Left column: two charts.
        left_x, left_w = Inches(0.6), Inches(6.9)
        self._add_price_chart(s, "近30日价格走势", p.price_30d, 30, left_x,
                              Inches(1.65), left_w, Inches(2.7), "day")
        self._add_price_chart(s, "近12个月价格走势", p.price_12mo, 30, left_x,
                              Inches(4.5), left_w, Inches(2.2), "month")

        # Right column: stacked analysis + forecast.
        rx, rw = Inches(7.7), Inches(5.0)
        self._add_analysis_column(s, p, rx, rw)

    def _add_kpi_chips(self, s, p: WeeklyReportProduct) -> None:
        t = self.theme
        change = p.change_pct_7d
        change_color = t.muted
        if change is not None:
            change_color = _UP_COLOR if change > 0 else (_DOWN_COLOR if change < 0 else t.muted)
        f7 = p.forecast_7d or {}
        rng = ""
        if f7.get("bear") is not None and f7.get("bull") is not None:
            rng = f"{_fmt_price(f7['bear'])}~{_fmt_price(f7['bull'])}"
        chips = [
            ("现价 元/吨", _fmt_price(p.current_price), t.text),
            ("7日变动", _fmt_change(change), change_color),
            ("预测区间", rng or "—", t.text),
        ]
        chip_w = Inches(1.7)
        gap = Inches(0.12)
        y = Inches(0.45)
        h = Inches(0.85)
        for i, (label, val, color) in enumerate(chips):
            x = Inches(7.55) + i * (chip_w + gap)
            box = _add_rect(s, x, y, chip_w, h, fill=t.band_bg, border=t.border,
                            radius_in=0.08)
            tf = box.text_frame
            tf.word_wrap = True
            p1 = tf.paragraphs[0]
            p1.alignment = PP_ALIGN.CENTER
            r1 = p1.add_run()
            r1.text = label
            r1.font.size = Pt(9)
            r1.font.color.rgb = t.muted
            r1.font.name = t.font_body
            p2 = tf.add_paragraph()
            p2.alignment = PP_ALIGN.CENTER
            r2 = p2.add_run()
            r2.text = val
            r2.font.size = Pt(14)
            r2.font.bold = True
            r2.font.color.rgb = color
            r2.font.name = t.font_body

    def _add_analysis_column(self, s, p: WeeklyReportProduct, x, width) -> None:
        t = self.theme
        w_in = width / Inches(1)
        # (label, text, label_top_in, body_height_in)
        sections = [
            ("市场分析", p.market_analysis, 1.55, 1.70),
            ("AI 决策", p.ai_decision, 3.65, 1.70),
        ]
        for label, text, top_in, max_h in sections:
            _add_textbox(s, x, Inches(top_in), width, Inches(0.28),
                         text=label, size=13, bold=True, color=t.primary_dark,
                         font_name=t.font_heading)
            if text:
                # Never truncate: auto-shrink the font so the full text fits
                # (falling back to TEXT_TO_FIT_SHAPE for the last few points).
                fitted, size = self._fit_text_size(text, w_in, max_h,
                                                   start=11, floor=7)
                self._add_markdown_box(
                    s, x, Inches(top_in + 0.3), width, Inches(max_h),
                    fitted, size=size, color=t.text, font_name=t.font_body,
                )
        # Forecast table (ends just above the 7.05" footer).
