    @staticmethod
    def _thin_category_labels(chart, n: int) -> None:
        if n <= 12:
            return
        skip = max(2, math.ceil(n / 8))
        try:
            cat_el = chart.category_axis._element
            for tag in ("c:tickLblSkip", "c:tickMarkSkip"):
                for el in cat_el.findall(qn(tag)):
                    cat_el.remove(el)
            for tag, val in (("c:tickLblSkip", skip), ("c:tickMarkSkip", skip)):
                el = cat_el.makeelement(qn(tag), {"val": str(val)})
                anchor = None
                for child in cat_el:
                    if child.tag in (qn("c:noMultiLvlLbl"), qn("c:extLst")):
                        anchor = child
                        break
                if anchor is not None:
                    anchor.addprevious(el)
                else:
                    cat_el.append(el)
        except Exception:
            pass

