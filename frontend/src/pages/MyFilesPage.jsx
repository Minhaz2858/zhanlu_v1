import { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useLanguage } from '@/lib/LanguageProvider';
import { base44 } from '@/api/base44Client';
import { useTranslate } from '@/lib/useTranslate';
import PageHeader from '@/components/PageHeader';
import FilesView from '@/components/files/FilesView';
import { FileText, Database, Sparkles } from 'lucide-react';

/**
 * MyFilesPage — centralised view of everything an agent has built or
 * generated for the current user.
 *
 * Sections:
 *   1. Knowledge Bases — quick links to KBs indexed/curated by agents.
 *   2. Agent Outputs (UserFile rows) — the main section, handled by
 *      FilesView which groups and filters by file_type.
 *
 * Reuses existing entity list APIs so that multi-tenant RBAC +
 * resource_shares filtering apply automatically.
 */
export default function MyFilesPage() {
  const { lang } = useLanguage();
  const isEn = lang === 'en';
  const navigate = useNavigate();
  const [kbs, setKbs] = useState([]);

  useEffect(() => {
    let cancelled = false;
    async function load() {
      try {
        const kbList = await base44.entities.KnowledgeBase.list('-updated_date', 50).catch(() => []);
        if (!cancelled) setKbs(kbList);
      } catch {
        // non-fatal — the FilesView is the primary content
      }
    }
    load();
    return () => { cancelled = true; };
  }, []);

  const translate = useTranslate(
    kbs.map((k) => k.name).filter(Boolean),
    lang
  );

  return (
    <div className="h-full overflow-y-auto px-8 py-8">
      <PageHeader
        title={isEn ? 'My Files' : '我的文件'}
        subtitle={isEn
          ? 'Every resource and asset your agents have built or generated — reports, automation outputs and more.'
          : '你的智能体创建或生成的全部资源与资产 — 报表、自动化产物等。'}
      />
      <div className="mt-2 mb-6 inline-flex items-center gap-1.5 rounded-full bg-secondary px-2.5 py-1 text-xs text-muted-foreground">
        <Sparkles className="h-3 w-3" />
        <span>{isEn ? 'Generated by agents' : '由智能体生成'}</span>
      </div>

      {/* Knowledge Bases — agent-indexed sources */}
      {kbs.length > 0 && (
        <section className="mb-10">
          <h2 className="mb-3 flex items-center gap-2 font-display text-base font-semibold text-foreground">
            <Database className="h-4 w-4" />
            {isEn ? 'Knowledge Bases' : '知识库'}
            <span className="text-xs font-normal text-muted-foreground">({kbs.length})</span>
          </h2>
          <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4">
            {kbs.map((k) => (
              <button
                key={k.id}
                onClick={() => navigate(`/my-space/kb/${k.id}`)}
                className="flex items-start gap-3 rounded-lg border border-border bg-card p-3 text-left transition-colors hover:bg-secondary"
              >
                <Database className="mt-0.5 h-4 w-4 shrink-0 text-muted-foreground" />
                <div className="min-w-0">
                  <div className="truncate text-sm font-medium text-foreground">
                    {translate(k.name) || k.name}
                  </div>
                  {k.status && (
                    <div className="mt-0.5 text-xs text-muted-foreground">{k.status}</div>
                  )}
                </div>
              </button>
            ))}
          </div>
        </section>
      )}

      {/* Primary section: agent-generated files (UserFile rows) */}
      <section>
        <h2 className="mb-3 flex items-center gap-2 font-display text-base font-semibold text-foreground">
          <FileText className="h-4 w-4" />
          {isEn ? 'Agent Outputs' : '智能体产物'}
        </h2>
        <FilesView />
      </section>
    </div>
  );
}
